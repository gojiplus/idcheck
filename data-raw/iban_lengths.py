"""Writes src/iban_lengths.h, and the same table as a test fixture: the IBAN
length of each country in SWIFT's IBAN registry, as packaged by schwifty
(MIT), official entries only.

    uv run --no-project --with schwifty python data-raw/iban_lengths.py
"""
import importlib.metadata
import json
import pathlib

import schwifty

registry = pathlib.Path(schwifty.__file__).parent / "iban_registry" / "generated.json"
lengths = {cc: spec["iban_length"] for cc, spec in json.loads(registry.read_text()).items()}
rows = ",\n".join(f'    {{"{cc}", {n}}}' for cc, n in sorted(lengths.items()))
version = importlib.metadata.version("schwifty")
pathlib.Path("src/iban_lengths.h").write_text(f"""// Generated by data-raw/iban_lengths.py from SWIFT's IBAN registry as packaged
// by schwifty {version}. Do not edit by hand.
#pragma once

struct IbanLength {{
  char country[3];
  int length;
}};

const IbanLength kIbanLengths[] = {{
{rows}
}};
""")
pathlib.Path("tests/testthat/iban_lengths.csv").write_text(
    "country,length\n" + "".join(f"{cc},{n}\n" for cc, n in sorted(lengths.items()))
)
print(len(lengths), "countries, longest", max(lengths.values()))
